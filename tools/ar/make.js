// Builds the AR pages into docs/ar/: copies ar/*.html, the libraries (three.js, MindAR, model-viewer)
// and writes docs/ar/sets.js from tools/ar/sets.config.js + the book data (texts copied from the book).
// Also writes tools/voice/ar.json (texts to record with the natural voice: python3 tools/voice-make.py ...).
// Usage: node tools/ar/make.js          (run tools/ar/render.js first for models + page targets)
const fs = require("fs"), path = require("path"), vm = require("vm");
const R = path.join(__dirname, "..", ".."), NM = path.join(R, "node_modules"), OUT = path.join(R, "docs", "ar");
const SETS = require("./sets.config.js");

const plain = (s) => String(s).replace(/\[\[|\]\]/g, "").replace(/\*/g, "");
function hashStr(s) { let x = 2166136261; for (let i = 0; i < s.length; i++) { x ^= s.charCodeAt(i); x = Math.imul(x, 16777619); } return x >>> 0; }
const vkey = (t) => { const k = plain(t).replace(/\s+/g, " ").trim(); return hashStr(k).toString(36) + k.length.toString(36); };

function loadBook(bid) {
  const ctx = { window: {}, console }; ctx.window = ctx; vm.createContext(ctx);
  vm.runInContext(fs.readFileSync(path.join(R, "books", bid, "book.js"), "utf8"), ctx);
  fs.readdirSync(path.join(R, "books", bid, "data")).filter((f) => /^u\d+\.js$/.test(f)).forEach((f) => vm.runInContext(fs.readFileSync(path.join(R, "books", bid, "data", f), "utf8"), ctx));
  return ctx.BOOK;
}
const readingParas = (l) => { const out = []; l.sections.filter((s) => s.type === "reading").forEach((s) => { (s.paras || []).forEach((p) => out.push(plain(p))); (s.blocks || []).forEach((b) => b.paras.forEach((p) => out.push(plain(p)))); }); return out; };
const sentences = (t) => t.split(/(?<=[.!?”])\s+(?=[A-Z“"])/);

const voice = {}, out = {};
for (const [sid, cfg] of Object.entries(SETS)) {
  const B = loadBook(cfg.book), unit = B.units.find((u) => u.id === cfg.unit);
  const L = (id) => unit.lessons.find((l) => l.id === id);
  const s = { title: cfg.title, titleAr: cfg.titleAr, book: cfg.book, bookUrl: "../" + cfg.book + "/index.html", targets: sid + ".mind", pages: [], models: {} };
  for (const pg of cfg.pages) {
    const first = L(pg.open[0]);
    const p = { page: pg.page, title: pg.title || first.title, open: pg.open.map((id) => ({ id, title: L(id).title, num: L(id).num })), models: pg.models };
    if (pg.read) { p.read = readingParas(L(pg.read)); p.read.forEach((t) => (voice[vkey(t)] = t)); }
    s.pages.push(p);
  }
  for (const [mid, m] of Object.entries(cfg.models)) {
    let sentence = null;
    if (m.find) { sentence = readingParas(L(m.lesson)).flatMap(sentences).find((x) => x.includes(m.find)); if (!sentence) throw new Error(sid + ": no sentence for " + mid); }
    s.models[mid] = { word: m.word, ar: m.ar, page: m.page, lesson: m.lesson, sentence };
    voice[vkey(m.word)] = m.word; if (sentence) voice[vkey(sentence)] = sentence;
  }
  out[sid] = s;
}
fs.mkdirSync(path.join(R, "tools", "voice"), { recursive: true });
fs.writeFileSync(path.join(R, "tools", "voice", "ar.json"), JSON.stringify(voice));
const have = Object.keys(voice).filter((k) => fs.existsSync(path.join(R, "docs", "voice", k + ".mp3")));
Object.values(out).forEach((s) => (s.voice = have));

fs.mkdirSync(path.join(OUT, "lib", "addons", "renderers"), { recursive: true });
const cp = (a, b) => fs.copyFileSync(path.join(NM, a), path.join(OUT, "lib", b));
cp("three/build/three.module.min.js", "three.module.min.js");
cp("three/examples/jsm/renderers/CSS3DRenderer.js", "addons/renderers/CSS3DRenderer.js");
for (const f of fs.readdirSync(path.join(NM, "mind-ar/dist"))) if (/^(mindar-image-three\.prod|controller-mGt1s8dJ|ui-fBadYuor)\.js$/.test(f)) cp("mind-ar/dist/" + f, f);
cp("@google/model-viewer/dist/model-viewer.min.js", "model-viewer.min.js");
fs.copyFileSync(path.join(__dirname, "models.js"), path.join(OUT, "lib", "models.js"));
for (const f of fs.readdirSync(path.join(R, "ar"))) fs.copyFileSync(path.join(R, "ar", f), path.join(OUT, f));
fs.writeFileSync(path.join(OUT, "sets.js"), "/* Generated by tools/ar/make.js from tools/ar/sets.config.js and the book data. */\nwindow.AR_SETS = " + JSON.stringify(out, null, 1) + ";\n");
console.log("docs/ar: " + Object.keys(out).join(", ") + " · voice " + have.length + "/" + Object.keys(voice).length + " recorded");
