// Build books/g8/data/glossary.js from the book's "Words to Remember" (pp. 96–99, books/g8/src/words-to-remember.txt).
// Meanings come from the lessons' vocabulary cards (written for the app, not printed in the book) and are marked as such.
const fs = require("fs"), path = require("path");
const B = path.join(__dirname, "..", "books", "g8");
global.BOOK = { units: [], addUnit(u) { this.units.push(u); } };
fs.readdirSync(path.join(B, "data")).filter((f) => /^u\d+\.js$/.test(f)).forEach((f) => eval(fs.readFileSync(path.join(B, "data", f), "utf8")));
const defs = {};
BOOK.units.forEach((u) => u.lessons.forEach((l) => (l.vocab || []).forEach((v) => { const k = v.w.toLowerCase(); if (!defs[k]) defs[k] = v.def; })));
const POS = { N: "noun", V: "verb", Adj: "adjective", Adv: "adverb", PhV: "phrasal verb", Preposition: "preposition" };
const out = fs.readFileSync(path.join(B, "src", "words-to-remember.txt"), "utf8").split("\n").filter((x) => x && !x.startsWith("#")).map((line) => {
  const [page, unit, w, pos] = line.split("|");
  const k = w.toLowerCase(), alt = k.split("/")[0].trim();
  const def = defs[k] || defs[alt] || defs[k.replace(/ (in|on|of|out|down)$/, "")] || null;
  const e = { w, pos: POS[pos] || pos, unit: +unit, page: +page };
  if (def) { e.def = def; e.defExtra = true; }
  return e;
}).sort((a, b) => a.w.localeCompare(b.w));
fs.writeFileSync(path.join(B, "data", "glossary.js"), "/* Generated by tools/g8-glossary.js — do not edit by hand. */\nBOOK.glossaryNote = \"The book’s word lists for every unit (pages 96–99). Short meanings are added to help you; they are not printed in the book.\";\nBOOK.glossary = " + JSON.stringify(out, null, 1) + ";\n");
console.log(out.length + " words, " + out.filter((e) => e.def).length + " with a meaning");
