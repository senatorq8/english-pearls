// Builds books/<book>/data/glossary.js from the lessons' vocabulary (for books whose glossary pages are not available).
// Usage: node tools/vocab-glossary.js g8
const fs = require("fs"), path = require("path"), vm = require("vm");
const bid = process.argv[2]; if (!bid) { console.error("usage: node tools/vocab-glossary.js <book>"); process.exit(1); }
const R = path.join(__dirname, ".."), dir = path.join(R, "books", bid, "data");
const ctx = { console }; ctx.window = ctx; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(R, "books", bid, "book.js"), "utf8"), ctx);
fs.readdirSync(dir).filter((f) => /^u\d+\.js$/.test(f)).sort((a, b) => parseInt(a.slice(1)) - parseInt(b.slice(1))).forEach((f) => vm.runInContext(fs.readFileSync(path.join(dir, f), "utf8"), ctx));
const seen = new Set(), out = [];
ctx.BOOK.units.sort((a, b) => a.num - b.num).forEach((u) => u.lessons.forEach((l) => (l.vocab || []).forEach((v) => {
  const k = v.w.toLowerCase(); if (seen.has(k)) return; seen.add(k);
  out.push({ w: v.w, pos: v.pos, ipa: v.ipa, unit: u.num, page: l.pages ? l.pages[0] : undefined, def: v.def, defExtra: true });
})));
out.sort((a, b) => a.w.localeCompare(b.w));
fs.writeFileSync(path.join(dir, "glossary.js"), "/* Generated by tools/vocab-glossary.js from the lessons' vocabulary — do not edit by hand. */\n" +
  "BOOK.glossaryNote = " + JSON.stringify("The new words from every lesson. The short meanings are added to help you; they are not printed in the book.") + ";\n" +
  "BOOK.glossary = " + JSON.stringify(out, null, 1) + ";\n");
console.log(bid + ": " + out.length + " words");
